'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const script=fs.readFileSync(path.join(__dirname,'../scripts/order_documents.js'),'utf8');
const admin=fs.readFileSync(path.join(__dirname,'../admin.html'),'utf8');
const sandbox={window:{},state:{orders:[],products:[]},localStorage:{getItem:()=>null,setItem:()=>{}}};
vm.runInNewContext(script,sandbox,{filename:'order_documents.js',timeout:2000});
const {calculateRows,renderDocument}=sandbox.window.IrounOrderDocuments;
const included=calculateRows([{name:'과세',quantity:2,unitPrice:1100,taxType:'included'}]);
assert.equal(included.total,2200);
assert.equal(included.supplyTotal,2000);
assert.equal(included.vatTotal,200);
const mixed=calculateRows([{name:'별도',quantity:3,unitPrice:1000,taxType:'excluded'},{name:'면세',quantity:2,unitPrice:500,taxType:'exempt'}]);
assert.equal(mixed.total,4300);
assert.equal(mixed.supplyTotal,4000);
assert.equal(mixed.vatTotal,300);
for(const bad of ['',-1,NaN])assert.throws(()=>calculateRows([{name:'오류',quantity:1,unitPrice:bad,taxType:'exempt'}]));
assert.throws(()=>calculateRows([{name:'오류',quantity:0,unitPrice:10,taxType:'exempt'}]));
assert.throws(()=>calculateRows([{name:'오류',quantity:1,unitPrice:10,taxType:'unknown'}]));
const sample={rows:[{name:'상품',quantity:2,unitPrice:1000,supply:2000,vat:0,amount:2000}],orderNo:'O1',date:'2026-10-31',seller:{name:'이로운과자점'},buyer:{name:'센터'}};
const delivery=renderDocument({...sample,type:'delivery'});
const transaction=renderDocument({...sample,type:'transaction',supplyTotal:2000,vatTotal:0,total:2000});
assert.match(delivery,/납품명세표/);
assert.doesNotMatch(delivery,/단가<\/th>|공급가액<\/th>|부가세<\/th>/);
assert.match(transaction,/거래명세표/);
assert.match(transaction,/공급가액<\/th>/);
assert.match(transaction,/합계 2,000원/);
assert.doesNotMatch(renderDocument({...sample,type:'delivery',rows:[{name:'<script>bad</script>',quantity:1}]}),/<script>bad<\/script>/);
assert.equal((admin.match(/명세표 출력/g)||[]).length,2);
assert.match(admin,/<script src="scripts\/order_documents\.js"><\/script>/);
console.log('order_documents: all checks passed');
